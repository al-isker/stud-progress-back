/**
 * Строка документа с визуальными атрибутами — внутреннее представление (IR),
 * с которым работает распознавание. Не зависит от исходного формата документа.
 */
export interface DocLine {
	/** Номер страницы, начиная с 1. */
	page: number;
	/** Базовая линия текста в координатах страницы (ось Y направлена вверх). */
	y: number;
	x0: number;
	x1: number;
	/** Кегль (максимальный по элементам строки). */
	size: number;
	text: string;
	/** Доля текста строки, набранного жирным шрифтом (0..1). */
	boldFrac: number;
	/** Доля текста строки, набранного курсивом (0..1). */
	italicFrac: number;
	/** Преобладающий цвет текста строки (#rrggbb) или null, если определить не удалось. */
	color: string | null;
	/** Доля ширины строки, накрытая цветным выделением: заливка, картинка-подложка, аннотация. */
	highlightFrac: number;
	/** Вертикальный зазор до предыдущей строки той же страницы (null для первой на странице). */
	gapBefore: number | null;
}
